// Bundles scripts/viewer/entry.js (three.js + OrbitControls) into a single self-contained HTML string:
//   lib/3d-lab/viewerHtml.generated.ts
// Run with `npm run build:3d-viewer` after changing the viewer. three.js is a dev dependency only; the app
// ships this pre-built string, so no extra native module is needed.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const result = await build({
  entryPoints: [join(root, 'scripts/viewer/entry.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2018'],
  write: false,
  legalComments: 'none',
});

const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
<style>
  html, body { margin: 0; padding: 0; height: 100%; overflow: hidden; background: #eef1f5; -webkit-user-select: none; user-select: none; -webkit-touch-callout: none; }
  #stage { position: fixed; inset: 0; touch-action: none; }
  canvas { display: block; outline: none; touch-action: none; }
</style>
</head>
<body>
<div id="stage"></div>
<script>${script}</script>
</body>
</html>`;

const ts = `// Generated by scripts/build-3d-viewer.mjs - do not edit by hand.\nexport const VIEWER_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'lib/3d-lab/viewerHtml.generated.ts'), ts);
console.log(`viewer bundle: ${(script.length / 1024).toFixed(0)} KB script, ${(ts.length / 1024).toFixed(0)} KB module`);
