#!/usr/bin/env python3
"""
Trace the company logo PNG into a clean vector outline for the 3D Lab engraving.

  python3 scripts/trace-logo.py "<path to IMU+ (Black).png>"

Outputs
  assets/3d-lab/imu-logo.svg      vector outline (the project asset)
  lib/3d-lab/logoData.ts          the same path data as a TS module (used at runtime)

The (R) mark is erased before tracing: it is far too small to engrave at 0.35 mm.
Requires: pip install potracer pillow numpy
"""
import sys, json, os
import numpy as np
from PIL import Image, ImageFilter
import potrace

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Downloads/IMU+® (Black)_20221104.png')
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

img = Image.open(src).convert('RGBA')
bg = Image.new('RGBA', img.size, (255, 255, 255, 255))
bg.alpha_composite(img)
gray = np.array(bg.convert('L'))
H, W = gray.shape
mask = gray < 128

# Erase the (R) mark: everything right of x=0.83*W and below y=0.78*H (the 'u' ends at ~0.81*W)
mask[int(0.78 * H):, int(0.83 * W):] = False
ys, xs = np.where(mask)
bbox = (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)
print('image', W, H, 'logo bbox', bbox)

# potracer treats the bright pixels as the foreground, so trace the inverse of the black-logo mask
bm = potrace.Bitmap(~mask)
plist = bm.trace(turdsize=20, turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY,
                 alphamax=1.0, opticurve=True, opttolerance=0.4)

def fmt(v):
    return ('%.2f' % v).rstrip('0').rstrip('.')

d_parts = []
n_curves = 0
for curve in plist:
    n_curves += 1
    s = curve.start_point
    d_parts.append('M%s %s' % (fmt(s.x), fmt(s.y)))
    for seg in curve.segments:
        if seg.is_corner:
            d_parts.append('L%s %s' % (fmt(seg.c.x), fmt(seg.c.y)))
            d_parts.append('L%s %s' % (fmt(seg.end_point.x), fmt(seg.end_point.y)))
        else:
            d_parts.append('C%s %s %s %s %s %s' % (fmt(seg.c1.x), fmt(seg.c1.y), fmt(seg.c2.x), fmt(seg.c2.y),
                                                 fmt(seg.end_point.x), fmt(seg.end_point.y)))
    d_parts.append('Z')
d = ''.join(d_parts)
print('curves', n_curves, 'path chars', len(d))

# --- minimum feature size (px), measured with square openings / closings on the raster -------------
def erode(a, k):
    im = Image.fromarray((a * 255).astype('uint8'))
    return np.array(im.filter(ImageFilter.MinFilter(k))) > 127
def dilate(a, k):
    im = Image.fromarray((a * 255).astype('uint8'))
    return np.array(im.filter(ImageFilter.MaxFilter(k))) > 127

crop = mask[bbox[1]:bbox[3], bbox[0]:bbox[2]]
total_black = crop.sum()

def thin_width(binary, ref_area, frac=0.002):
    # smallest odd kernel size k whose opening removes a noticeable amount of the shape
    for k in range(3, 400, 2):
        opened = dilate(erode(binary, k), k)
        removed = (binary & ~opened).sum()
        if removed > frac * ref_area:
            return k - 2
    return 400

# pad so closings at the border do not matter
padded = np.pad(crop, 40)
min_stroke_px = thin_width(padded, total_black)
white = ~padded
# restrict to the white pixels that lie between black parts (not the open background): close with a big kernel
bounded = dilate(erode(~dilate(erode(white, 3), 3), 3), 3)  # unused helper kept simple
min_gap_px = thin_width(white, total_black)
print('min stroke px', min_stroke_px, 'min gap px', min_gap_px)

vw, vh = bbox[2] - bbox[0], bbox[3] - bbox[1]
svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="%d %d %d %d" width="%d" height="%d">'
       '<path fill="#000" fill-rule="evenodd" d="%s"/></svg>\n') % (bbox[0], bbox[1], vw, vh, vw, vh, d)
os.makedirs(os.path.join(root, 'assets/3d-lab'), exist_ok=True)
open(os.path.join(root, 'assets/3d-lab/imu-logo.svg'), 'w').write(svg)

ts = ('// Generated by scripts/trace-logo.py from the company logo PNG. Do not edit by hand.\n'
      '// Coordinates are source pixels (y points down). The (R) mark has been removed.\n'
      'export const LOGO_BBOX = { x0: %d, y0: %d, width: %d, height: %d } as const;\n'
      '// Thinnest features measured on the raster, in source pixels (strokes = filled, gaps = slits between parts).\n'
      'export const LOGO_MIN_STROKE_PX = %d;\n'
      'export const LOGO_MIN_GAP_PX = %d;\n'
      'export const LOGO_PATH = %s;\n') % (bbox[0], bbox[1], vw, vh, max(min_stroke_px, 1), max(min_gap_px, 1), json.dumps(d))
open(os.path.join(root, 'lib/3d-lab/logoData.ts'), 'w').write(ts)
print('wrote svg + logoData.ts')
